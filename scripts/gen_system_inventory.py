#!/usr/bin/env python3
"""Generate docs/SYSTEM_INVENTORY.generated.md from repo files only.

Deterministic (sorted, no timestamps). Usage:
    python3 scripts/gen_system_inventory.py           # write the file
    python3 scripts/gen_system_inventory.py --check   # exit 1 if it differs
"""

import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "SYSTEM_INVENTORY.generated.md"
COMPOSE = "docker-compose.prod.yml"
NGINX_FILES = [
    "output_apps/nginx_config/nginx.conf",
    "nginx.conf",
    "nginx_split.conf",
    "production_bundle/nginx/nginx.conf",
]
BACKEND_PKG = "output_apps/enterprise_hub/package.json"
FRONTEND_PKG = "output_apps/enterprise_hub/frontend/package.json"
NPM_KEYS = ["next", "react", "tailwindcss", "@nestjs/core", "typescript"]
PY_KEYS = ["fastapi", "qdrant-client", "httpx", "pydantic"]


def parse_ports(service):
    """Return sorted published port strings of a compose service dict."""
    out = []
    for p in service.get("ports") or []:
        out.append(str(p))
    return sorted(out)


def parse_compose(text):
    """Return {service: {"image": str, "ports": [..], "env": [names]}}."""
    data = yaml.safe_load(text) or {}
    result = {}
    for name, svc in (data.get("services") or {}).items():
        svc = svc or {}
        image = svc.get("image")
        if not image and svc.get("build"):
            image = "build"
        env_names = set(re.findall(r"\$\{([A-Za-z_][A-Za-z0-9_]*)", yaml.safe_dump(svc)))
        env = svc.get("environment") or []
        if isinstance(env, dict):
            env_names.update(env.keys())
        else:
            for item in env:
                env_names.add(str(item).split("=", 1)[0])
        result[name] = {
            "image": image or "",
            "ports": parse_ports(svc),
            "env": sorted(env_names),
        }
    return result


def parse_server_names(text):
    """Return sorted unique server_name values from nginx config text."""
    names = set()
    for m in re.finditer(r"\bserver_name\s+([^;]+);", text):
        names.update(m.group(1).split())
    return sorted(names)


def parse_workflow(text):
    """Return (name, sorted trigger names) of a workflow YAML string."""
    data = yaml.safe_load(text) or {}
    name = data.get("name", "")
    on = data.get("on", data.get(True))
    if isinstance(on, str):
        triggers = [on]
    elif isinstance(on, list):
        triggers = [str(x) for x in on]
    elif isinstance(on, dict):
        triggers = [str(k) for k in on]
    else:
        triggers = []
    return str(name), sorted(triggers)


def parse_package_versions(text, keys):
    """Return (name, {key: version}) from package.json text."""
    data = json.loads(text)
    found = {}
    for section in ("dependencies", "devDependencies"):
        for k, v in (data.get(section) or {}).items():
            if k in keys:
                found[k] = v
    return data.get("name", ""), found


def parse_python_deps(text, keys):
    """Find key deps in requirements-like text (pyproject list or pip install lines)."""
    found = {}
    for key in keys:
        m = re.search(
            r"(?<![\w-])" + re.escape(key) + r"(?![\w-])(\s*(?:[=<>~!]=?[^\s\"',]+)?)", text
        )
        if m:
            found[key] = m.group(1).strip() or "(unpinned)"
    return found


def parse_requires_python(text):
    m = re.search(r'requires-python\s*=\s*"([^"]+)"', text)
    return m.group(1) if m else ""


def parse_dockerfile_python(text):
    m = re.search(r"^FROM\s+python:([^\s]+)", text, re.MULTILINE)
    return m.group(1) if m else ""


def parse_model_roles(text):
    """Return {role: [model ids]} from models.yaml text."""
    data = yaml.safe_load(text) or {}
    roles = {}
    for role, spec in (data.get("roles") or {}).items():
        roles[role] = [m.get("id", "") for m in (spec or {}).get("models") or []]
    return roles


def _read(rel):
    p = ROOT / rel
    return p.read_text(encoding="utf-8") if p.exists() else None


def render():
    lines = [
        "# System inventory (generated)",
        "",
        "Generated by `scripts/gen_system_inventory.py` from repo files only. Do not edit by hand;",
        "run `python3 scripts/gen_system_inventory.py` (CI-style check: `--check`).",
        "",
    ]
    compose_text = _read(COMPOSE)
    compose = parse_compose(compose_text) if compose_text else {}
    lines += ["## Compose services (docker-compose.prod.yml)", "", "| Service | Image | Published ports |", "| --- | --- | --- |"]
    for name in sorted(compose):
        s = compose[name]
        ports = "<br>".join(s["ports"]) or "-"
        lines.append(f"| {name} | {s['image']} | {ports} |")
    lines += ["", "## Environment variable names referenced in docker-compose.prod.yml", ""]
    env = sorted({n for s in compose.values() for n in s["env"]})
    lines += [", ".join(f"`{n}`" for n in env) or "-", ""]

    lines += ["## nginx server_name values", "", "| Config file | server_name values |", "| --- | --- |"]
    for rel in sorted(NGINX_FILES):
        t = _read(rel)
        if t is not None:
            lines.append(f"| {rel} | {', '.join(parse_server_names(t))} |")
    lines.append("")

    lines += ["## GitHub workflows", "", "| File | name | Triggers |", "| --- | --- | --- |"]
    for f in sorted((ROOT / ".github" / "workflows").glob("*.yml")):
        name, trig = parse_workflow(f.read_text(encoding="utf-8"))
        lines.append(f"| {f.name} | {name} | {', '.join(trig)} |")
    lines.append("")

    lines += ["## Packages", "", "| Package | Name | Versions |", "| --- | --- | --- |"]
    for label, rel in (("backend", BACKEND_PKG), ("frontend", FRONTEND_PKG)):
        t = _read(rel)
        if t is None:
            continue
        name, vers = parse_package_versions(t, NPM_KEYS)
        lines.append(f"| {label} | {name} | " + ", ".join(f"{k} {vers[k]}" for k in sorted(vers)) + " |")
    lines.append("")

    pyproject = _read("pyproject.toml") or ""
    dockerfile = _read("Dockerfile.prod") or ""
    lines += ["## Python", ""]
    lines.append(f"- pyproject requires-python: `{parse_requires_python(pyproject) or 'n/a'}`")
    lines.append(f"- Dockerfile.prod base image: `python:{parse_dockerfile_python(dockerfile) or 'n/a'}`")
    for label, text in (("pyproject.toml", pyproject), ("Dockerfile.prod", dockerfile)):
        deps = parse_python_deps(text, PY_KEYS)
        shown = ", ".join(f"{k} {deps[k]}" for k in sorted(deps)) or "none of the key deps declared"
        lines.append(f"- {label}: {shown}")
    lines.append("")

    models = _read("config/models.yaml")
    lines += ["## Model roles (config/models.yaml)", "", "| Role | Model ids (first = primary) |", "| --- | --- |"]
    if models:
        roles = parse_model_roles(models)
        for role in sorted(roles):
            lines.append(f"| {role} | {', '.join(roles[role])} |")
    lines.append("")
    return "\n".join(lines)


def main(argv):
    content = render()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else None
        if current != content:
            print(f"{OUT.relative_to(ROOT)} is out of date; run scripts/gen_system_inventory.py")
            return 1
        return 0
    OUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
