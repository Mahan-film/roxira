def _get(url: str):
    with urllib.request.urlopen(url, timeout=15) as r:
        return json.loads(r.read().decode("utf-8"))


def _post(url: str, body: dict):
    data = json.dumps(body).encode("utf-8")
    req = urllib.request.Request(url, data=data, headers={"Content-Type": "application/json"}, method="POST")
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.loads(r.read().decode("utf-8"))


def _put(url: str, body: dict):
    data = json.dumps(body).encode("utf-8")
    req = urllib.request.Request(url, data=data, headers={"Content-Type": "application/json"}, method="PUT")
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.loads(r.read().decode("utf-8"))


def ensure_collection() -> None:
    try:
        info = _get(f"{QDRANT_URL}/collections/{COLLECTION}")
        print(f"[v2] collection exists: {info['result']['points_count']} points")
        return
    except urllib.error.HTTPError as exc:  # type: ignore[name-defined]
        if exc.code != 404:
            raise
    print(f"[v2] creating collection {COLLECTION} (size={VECTOR_SIZE}, cosine)")
    _put(f"{QDRANT_URL}/collections/{COLLECTION}", {
        "vectors": {"size": VECTOR_SIZE, "distance": "Cosine"},
    })


def embed_texts(texts: list[str]) -> list[list[float]]:
    from sentence_transformers import SentenceTransformer

    print("[v2] loading BAAI/bge-m3 (local, CPU) ...")
    model = SentenceTransformer("BAAI/bge-m3")
    vectors = model.encode(texts, normalize_embeddings=True, show_progress_bar=True)
    return [v.tolist() for v in vectors]


def build_points() -> list[dict]:
    texts = []
    metas = []
    for article_no, text in CHEQUE_LAW_ARTICLES:
        label = f"ماده {article_no}" if not isinstance(article_no, str) else f"ماده {article_no.replace('-mokarrar', ' مکرر')}"
        full_text = f"{label} قانون صدور چک (اصلاحی ۱۳۹۷): {text}"
        texts.append(full_text)
        content_hash = hashlib.md5(full_text.encode("utf-8")).hexdigest()
        metas.append({
            "law_name": "قانون صدور چک (اصلاحی ۱۳۹۷)",
            "law_type": "COMMERCIAL",
            "article_no": str(article_no),
            "article_label": label,
            "chapter": None,
            "approval_date": "1397-08-13",
            "status": "VALID",
            "is_active": True,
            "source_url": SOURCE_URL,
            "source_note": "paraphrase pending verbatim replacement from qavanin.ir/rc.majlis.ir",
            "text": full_text,
            "title": f"قانون صدور چک - {label}",
            "category": "COMMERCIAL",
            "content_hash": content_hash,
            "scope_tags": ["commercial", "cheque", "sayad"],
        })

    print("[v2] embedding {} articles ...".format(len(texts)))
    vectors = embed_texts(texts)

    points = []
    for meta, vector in zip(metas, vectors):
        point_id = str(uuid.uuid5(NAMESPACE, meta["content_hash"]))
        points.append({"id": point_id, "vector": vector, "payload": meta})
    return points


def upsert(points: list[dict]) -> None:
    resp = _put(f"{QDRANT_URL}/collections/{COLLECTION}/points?wait=true", {"points": points})
    print("[v2] upsert result:", resp.get("status"))


def main() -> None:
    ensure_collection()
    points = build_points()
    upsert(points)
    info = _get(f"{QDRANT_URL}/collections/{COLLECTION}")
    print(f"[v2] {COLLECTION} now has {info['result']['points_count']} points")


if __name__ == "__main__":
    main()
