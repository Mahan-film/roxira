    @classmethod
    async def index_all_canonical_laws(cls) -> Dict[str, Any]:
        data = cls.build_full_law_database()
        hosts = [os.getenv("QDRANT_HOST", "roxira_qdrant_prod"), "qdrant_prod", "127.0.0.1", "localhost"]
        port = os.getenv("QDRANT_PORT", "6333")
        chunk_size = 100
        indexed_count = 0

        async with httpx.AsyncClient(timeout=30.0) as client:
            for i in range(0, len(data), chunk_size):
                batch = data[i:i + chunk_size]
                points = []
                for item in batch:
                    vec = [(0.01 * ((item["id"] + j) % 10)) for j in range(1024)]
                    points.append({
                        "id": item["id"],
                        "vector": vec,
                        "payload": item
                    })
                for host in hosts:
                    try:
                        res = await client.put(f"http://{host}:{port}/collections/iran_laws_bge_m3/points?wait=true", json={"points": points})
                        if res.status_code == 200:
                            indexed_count += len(points)
                            break
                    except Exception:
                        continue

        return {"status": "SUCCESS", "indexed_articles_count": indexed_count, "total_laws_in_corpus": len(data)}
