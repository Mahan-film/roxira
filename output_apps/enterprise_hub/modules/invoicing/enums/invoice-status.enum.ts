/**
 * وضعیت‌های چرخه عمر صورتحساب مالیاتی (Tax Invoice).
 *
 * DRAFT:
 *   پیش‌نویس؛ فاکتور ایجاد شده ولی هنوز به‌صورت رسمی صادر/ثبت نشده است.
 * ISSUED:
 *   صادرشده؛ صورتحساب رسمی است و در دفاتر مالیاتی قابل استناد می‌باشد.
 * CANCELLED:
 *   ابطال‌شده؛ صورتحساب صادرشده توسط طرفین/سازمان ابطال شده و دیگر معتبر نیست.
 */
export enum InvoiceStatus {
  DRAFT = 'DRAFT',
  ISSUED = 'ISSUED',
  CANCELLED = 'CANCELLED',
}
