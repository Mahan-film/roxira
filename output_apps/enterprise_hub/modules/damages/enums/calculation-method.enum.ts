/**
 * روش‌های محاسبه خسارت تاخیر تادیه
 *
 * CPI_INDEX:
 *   محاسبه بر مبنای "شاخص قیمت کالاها و خدمات مصرفی" اعلامی بانک مرکزی
 *   موضوع ماده ۵۲۲ قانون آیین دادرسی دادگاه‌های عمومی و انقلاب در امور مدنی.
 *   فرمول: خسارت = اصل مبلغ × (شاخص روز پرداخت − شاخص روز سررسید) ÷ شاخص روز سررسید
 *
 * ANNUAL_RATE:
 *   محاسبه بر مبنای نرخ سود سالانه قراردادی/توافقی (مثلاً نرخ تسهیلات بانکی).
 *   فرمول: خسارت = اصل مبلغ × (نرخ سالانه ÷ ۱۰۰) × (تعداد روزهای تاخیر ÷ ۳۶۵)
 */
export enum DamageCalculationMethod {
  CPI_INDEX = 'CPI_INDEX',
  ANNUAL_RATE = 'ANNUAL_RATE',
}
